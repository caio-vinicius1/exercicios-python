a=input('Digite algo:\033[1;35m ')
print('\033[0m' , end='')
b=input('Digite novamente: \033[1;34m ')
print('\033[0m' , end='')
print(f'O tipo primitivo do valor \033[1;35m{a}\033[0m é:',type(a))
print(f'\033[1;35m{a}\033[0m Só tem espaços?',a.isspace())
print(f'\033[1;34m{b}\033[0m é um número?',b.isnumeric())
print(f'\033[1;35m{a}\033[0m é alfabético?',a.isalpha())
print(f'\033[1;35m{a}\033[0m está em maiúsculas?',a.isupper())
print('\033[1;34m{}\033[0m Está em minúsculas?'.format(b),b.islower())
print('A primeira letra de \033[1;35m{}\033[0m está maiúscula?'.format(a),a.istitle())
print('\033[1;35m{}\033[0m É alfanumérico?'.format(a),a.isalnum())
print('\033[1;34m{}\033[0m É alfanumérico?'.format(b),b.isalnum())