# Peça dois números ao usuário (lembre de converter com int() ou float()) e mostre a
# soma, a subtração, a multiplicação e a divisão
n1 = int(input('Digite um número: '))
n2 = int(input('Digite outro número: '))
soma = n1 + n2
subtracao = n1 - n2
multi = n1 * n2
divisao = n1 // n2
print(f'A soma dos dois valores {n1} e {n2} é: {soma}')
print(f'A subtração dos valores {n1} e {n2} é: {subtracao}')
print(f'A multiplicação dos valores {n1} e {n2} é: {multi}')
print(f'A divisão dos valores {n1} e {n2} é: {divisao}')
