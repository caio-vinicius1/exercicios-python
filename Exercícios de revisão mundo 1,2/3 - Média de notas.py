# Peça três notas, calcule a média e mostre o resultado com duas casas decimais (dica:
# f"{media:.2f}").
n1 = float(input('Digite a primeira nota: '))
n2 = float(input('Digite a segunda nota: '))
n3 = float(input('Digite a terceira nota: '))
media = (n1 + n2 + n3) / 3
print(f'A média entre as três notas é : {media:.2f}')
